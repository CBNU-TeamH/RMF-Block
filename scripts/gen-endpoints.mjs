#!/usr/bin/env node
// Renders docs/design/api.md's "Implemented endpoints" table from the code (#130): one row per
// route x method plus the WebSocket paths, so the built set can't drift from the prose.
// Default rewrites the block between the generated:endpoints markers; --check exits 1 if stale.
import fs from "node:fs";
import { pathToFileURL } from "node:url";
import { extractFacts } from "./lib/ast-facts.mjs";

const DOC = "docs/design/api.md";
const START = "<!-- generated:endpoints:start -->";
const END = "<!-- generated:endpoints:end -->";
const NOTE = "Generated by `node scripts/gen-endpoints.mjs` from the code — do not edit by hand.";

const files = (calls) => [...new Set(calls.map((c) => c.at.replace(/:\d+$/, "")))].sort().map((f) => `\`${f}\``).join(", ");

export function renderEndpoints(facts) {
  const { routes, wsPaths, matching } = facts;
  const rows = routes.flatMap((r) => r.methods.map((m) => {
    const calls = matching.calls.filter((c) => c.route === r.file && (c.method === m || c.method === null));
    const callers = calls.length ? files(calls) : r.path.startsWith("/api/internal/") ? "— (webhook)" : "— (no fetch caller; used as a URL)";
    return { m, p: r.path, h: r.file, callers };
  }));
  for (const w of wsPaths) rows.push({ m: "WS", p: w.value, h: w.at.replace(/:\d+$/, ""), callers: files(matching.calls.filter((c) => c.kind === "ws" && c.path === w.value)) || "—" });
  const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0); // not localeCompare: keep code-point order
  rows.sort((a, b) => cmp(a.p, b.p) || cmp(a.m, b.m));
  return [NOTE, "", "| Method | Path | Handler file | Client callers |", "| --- | --- | --- | --- |",
    ...rows.map((r) => `| \`${r.m}\` | \`${r.p}\` | \`${r.h}\` | ${r.callers} |`)].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const doc = fs.readFileSync(DOC, "utf8");
  const s = doc.indexOf(START), e = doc.indexOf(END);
  if (s < 0 || e < s) { console.error(`${DOC}: generated:endpoints markers missing`); process.exit(1); }
  const next = doc.slice(0, s + START.length) + "\n" + renderEndpoints(extractFacts()) + "\n" + doc.slice(e);
  if (next === doc) return;
  if (!check) return fs.writeFileSync(DOC, next);
  console.error(`${DOC}: endpoint table is stale — run node scripts/gen-endpoints.mjs`);
  process.exit(1);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
